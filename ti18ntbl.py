"""Generate C code for internationalization message table."""

import sys

NON_ASCII_MIN = 128


def encode_msg(msg: str, encode: str) -> str:
    """Encode a message string into a C-compatible string literal.

    escaping non-ASCII characters.
    """
    result: list[str] = []
    for ch in msg:
        code = ord(ch)
        if code < NON_ASCII_MIN:
            result.append(ch)
        else:
            result.extend([f"\\{b:03o}" for b in ch.encode(encode)])
    return "".join(result)


def literal_byte_len(body: str) -> int:
    """Count the bytes a string literal body contributes.

    C escapes are resolved to their single byte escape value, so the
    result is the length of the translated string token.  ISO C90 only
    requires compilers to accept literals up to 509 characters.
    """
    n = 0
    i = 0
    while i < len(body):
        if body[i] == "\\" and i + 1 < len(body):
            nxt = body[i + 1]
            if nxt in "01234567" and i + 4 <= len(body) and body[i + 2:i + 4].isdigit():
                i += 4
            else:
                i += 2
            n += 1
        else:
            i += 1
            n += 1
    return n


def generate_c_code(
    lang: str,
    encode: str,
    messages: list[tuple[str, list[str]]],
) -> list[str]:
    """Generate C code for internationalization message table."""
    func_name = f"lang_{lang.lower()}_init"
    out_lines = [
        "/* This file is automatically generated. Do not edit. */",
        f"/* Language: {lang}, Encoding: {encode} */",
        '#include "imessages.h"',
        "",
        f"#ifndef LANG_{lang.upper()}_H",
        f"#define LANG_{lang.upper()}_H",
        "",
        f"static void {func_name}(const char *table[MSG_COUNT])",
        "{",
    ]

    for msg_id, strings in messages:
        enc = [encode_msg(s, encode) for s in strings]
        total = sum(literal_byte_len(b) for b in enc)
        join = total > 509

        if join:
            out_lines.append(f"    table[{msg_id}] = msg_join(")
            for b in enc:
                out_lines.append(f"        \"{b}\",")
            out_lines.append("        (const char *)NULL);")
        elif len(enc) == 1:
            out_lines.append(f"    table[{msg_id}] = \"{enc[0]}\";")
        else:
            out_lines.append(f"    table[{msg_id}] =")
            for i, b in enumerate(enc):
                last = i == len(enc) - 1
                out_lines.append(f"        \"{b}\"" + (";" if last else ""))

    out_lines.extend(
        [
            "}",
            "#endif",
            "",
        ],
    )

    return out_lines


ARGS_COUNT = 2


def main() -> None:
    """Generate C code for internationalization message table."""
    if len(sys.argv) != ARGS_COUNT:
        sys.stderr.write("Usage: ti18ntbl <encoding>\n")
        sys.exit(1)
    encode = sys.argv[1]

    data: str = sys.stdin.read()
    parts = data.split("---")

    lang = "ERR"
    if parts and parts[0].strip():
        first_lines = parts[0].strip().splitlines()
        if first_lines:
            lang = first_lines[0].strip()

    messages: list[tuple[str, list[str]]] = []
    for part in parts[1:]:
        lines = [line for line in part.splitlines() if line.strip()]
        if not lines:
            continue

        msg_id = lines[0].strip()
        if not msg_id.startswith("MSG_"):
            sys.stderr.write(f"Error: Invalid message ID '{msg_id}'\n")
            sys.exit(1)

        strings: list[str] = []
        for line in lines[1:]:
            stripped = line.lstrip()
            if stripped.startswith('"'):
                # Drop the generator-level delimiters: emission re-quotes.
                if len(stripped) >= 2 and stripped.endswith('"'):
                    strings.append(stripped[1:-1])
                else:
                    strings.append(stripped)

        if strings:
            messages.append((msg_id, strings))

    out_lines = generate_c_code(lang, encode, messages)

    sys.stdout.write("\n".join(out_lines))
    sys.stderr.write(f"Generated {len(messages)} messages.\n")


if __name__ == "__main__":
    main()
